"""
Aggregate per-run benchmark records into mean +/- std tables in the README.

Renders the tables between the BENCHMARK_RESULTS markers.
Reads <results>/scenarios.json (written by run_matrix.py), groups by
(mode, scenario, model, controller), reduces the `repeats` to mean +/- std - the
precision signal - and writes Markdown tables. No git operations.
"""

import argparse
import json
from pathlib import Path
import statistics as st

# (json key, column header, unit, value format)
COLUMNS = [
    ('success', 'success', '', 'rate'),
    ('time_to_goal_s', 't_goal', 's', 'ms'),
    ('path_length_m', 'path', 'm', 'ms'),
    ('goal_error_m', 'goal_err', 'm', 'ms3'),
    ('cross_track_rms_m', 'ct_rms', 'm', 'ms3'),
    ('cross_track_max_m', 'ct_max', 'm', 'ms3'),
    # Controller-agnostic avoidance metrics (obstacle scenarios; n/a on the open cell).
    ('min_obstacle_gap_m', 'obs_gap', 'm', 'ms3'),
    ('collision', 'coll', '', 'rate'),
    ('solve_ms_p50', 'solve_p50', 'ms', 'ms3'),
    ('solve_ms_p95', 'solve_p95', 'ms', 'ms3'),
    ('solve_ms_max', 'solve_max', 'ms', 'ms3'),
    ('deadline_miss_rate', 'miss', '', 'pct'),
    ('mean_sqp_iters', 'sqp', '', 'ms'),
    ('mean_qp_iters_ext', 'qp_ext', '', 'ms'),
    ('infeasible_rate', 'infeas', '', 'pct'),
    ('max_obstacle_slack_m', 'slack', 'm', 'ms3'),
    # Process-resource metrics (mode b2; n/a where the run did not sample a process).
    ('control_rate_hz', 'rate', 'Hz', 'ms'),
    ('cpu_mean_pct', 'cpu', '%', 'ms'),
    ('rss_peak_mb', 'rss', 'MB', 'ms'),
    # Per-cycle controller compute time from the timing decorator (mode b2).
    ('compute_ms_p50', 'cmp_p50', 'ms', 'ms3'),
    ('compute_ms_p95', 'cmp_p95', 'ms', 'ms3'),
]


def fmt(kind, vals):
    nums = [v for v in vals if isinstance(v, (int, float))]
    if not nums:
        return 'n/a'
    mean = sum(nums) / len(nums)
    sd = st.pstdev(nums) if len(nums) > 1 else 0.0
    if kind == 'rate':
        return f'{mean * 100:.0f}%'
    if kind == 'pct':
        return f'{mean * 100:.1f}±{sd * 100:.1f}%'  # ascii-ok
    if kind == 'ms3':
        return f'{mean:.3f}±{sd:.3f}'  # ascii-ok
    return f'{mean:.2f}±{sd:.2f}'  # ascii-ok


def group_key(rec):
    return (rec.get('mode'), rec.get('scenario'), rec.get('model'),
            rec.get('controller', 'proxmpc'))


def build_tables(records):
    groups = {}
    for rec in records:
        groups.setdefault(group_key(rec), []).append(rec)

    modes = sorted({k[0] for k in groups})
    out = []
    for mode in modes:
        out.append(f'### Mode `{mode}`\n')
        header = '| scenario | model | controller | n | ' + ' | '.join(
            f"{h}{'['+u+']' if u else ''}" for _, h, u, _ in COLUMNS) + ' |'
        sep = '|' + '---|' * (4 + len(COLUMNS))
        out.append(header)
        out.append(sep)
        keys = sorted(k for k in groups if k[0] == mode)
        for k in keys:
            recs = groups[k]
            n = len(recs)
            cells = []
            for key, _h, _u, kind in COLUMNS:
                if key in ('success', 'collision'):
                    # Booleans (collision null on the open cell is dropped by fmt).
                    vals = [(1.0 if r.get(key) else 0.0) for r in recs
                            if key != 'collision' or r.get(key) is not None]
                else:
                    vals = [r.get(key) for r in recs]
                cells.append(fmt(kind, vals))
            out.append(f'| {k[1]} | {k[2]} | {k[3]} | {n} | ' + ' | '.join(cells) + ' |')
        out.append('')
    return '\n'.join(out)


START = '<!-- BENCHMARK_RESULTS_START -->'
END = '<!-- BENCHMARK_RESULTS_END -->'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--results-dir', default='')
    ap.add_argument('--readme', default='')
    args = ap.parse_args()

    pkg_root = Path(__file__).resolve().parents[1]
    results_dir = Path(args.results_dir) if args.results_dir else pkg_root / 'results'
    if not results_dir.exists():
        results_dir = Path.home() / 'ros2_ws' / 'src' / 'prox_mpc' / \
            'prox_mpc_benchmark' / 'results'
    readme = Path(args.readme) if args.readme else \
        results_dir.parent / 'README.md'

    index_path = results_dir / 'scenarios.json'
    records = json.load(open(index_path)) if index_path.exists() else []
    if not records:
        print('[aggregate] no records in scenarios.json')
        return 0

    tables = build_tables(records)
    block = (f'{START}\n\n'
             f'*Auto-generated by `aggregate.py` from `results/scenarios.json` '
             f'({len(records)} runs). Values are mean±std (population) over repeats - '  # ascii-ok
             f'the precision signal. Not committed.*\n\n'
             f'{tables}\n{END}')

    text = readme.read_text() if readme.exists() else '# prox_mpc_benchmark\n'
    if START in text and END in text:
        pre = text.split(START)[0]
        post = text.split(END)[1]
        text = pre + block + post
    else:
        text = text.rstrip() + '\n\n## Results\n\n' + block + '\n'
    readme.write_text(text)
    print(f'[aggregate] wrote {len(records)} runs into {readme}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
